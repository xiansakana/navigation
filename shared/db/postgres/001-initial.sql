CREATE FUNCTION advance_rbac_revision() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.revision = OLD.revision THEN
    NEW.revision := OLD.revision + 1;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER rbac_payload_revision BEFORE UPDATE OF payload ON rbac_snapshot
FOR EACH ROW EXECUTE FUNCTION advance_rbac_revision();
